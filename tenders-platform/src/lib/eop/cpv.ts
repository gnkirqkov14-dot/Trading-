export const CPV_OPTIONS = Object.entries(CPV_DIVISIONS).map(([code, name]) => ({
  code,
  name,
}));

export function cpvDivision(cpvCode: string | null | undefined): string | null {
  if (!cpvCode) return null;
  const division = cpvCode.replace(/\D/g, "").slice(0, 2);
  return division.length === 2 ? division : null;
}

export function divisionName(division: string | null | undefined): string {
  if (!division) return "Друго";
  return CPV_DIVISIONS[division] ?? `Раздел ${division}`;
}
