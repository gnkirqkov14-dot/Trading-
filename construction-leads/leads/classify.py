"""Груба класификация на обект по текста от разрешението и оценка
колко интересен е като търговска възможност (0–100)."""
from __future__ import annotations

import re

from .ksb import LEGAL_FORMS

KIND_RULES = [
    # (вид, регулярен израз) – първото съвпадение печели
    ("Фотоволтаици", r"фотоволтаич|фец|\bkwp\b"),
    # Фасадни работи по съществуващи сгради – важни за фасадни материали
    ("Фасадна реновация", r"енергийн\w* обновяване|енергийна ефективност|саниране|"
                          r"топлоизолац|фасад"),
    ("Преустройство / ремонт", r"преустройство|ремонт|реконструкция|укрепване|обновяване|"
                               r"промяна на предназначението|обединяване|обединение|разделяне|"
                               r"делба|саниране|енергийна ефективност|смяна на"),
    ("Надстрояване / пристрояване", r"надстро|пристро"),
    ("Инфраструктура", r"улиц|път|водопровод|канализац|кабел|трафопост|газопровод|"
                       r"топлопровод|\bмост|площадка|спортна площ|осветление|"
                       r"оптич|съоръжение|мачта|базова станция|приемно-предавателна"),
    ("Ново строителство", r"сград|комплекс|къща|офис|хотел|склад|логистич|"
                          r"производствен|търговск|училище|детска градина|болница"),
    ("Допълващо застрояване", r"допълващо|ограда|навес|гараж|постройка|басейн|ателие"),
]

BUILDING_RULES = [
    ("Смесено предназначение", r"смесено предназначение|многофункционал|жилищ\w* и офис|офиси и жилища"),
    # Еднофамилните първо: „еднофамилна жилищна сграда“ съдържа и „жилищна сграда“
    ("Жилищна – еднофамилна", r"еднофамилн|двуфамилн|къща|вилн"),
    ("Жилищна – многофамилна", r"многофамилн|жилищна сграда|жилищни сгради|жилищен комплекс|апартамент"),
    ("Офис / административна", r"офис|администрат|бизнес"),
    ("Търговска", r"търговск|магазин|мол|супермаркет|шоурум"),
    ("Хотел", r"хотел|апартхотел"),
    ("Логистика / промишленост", r"склад|логистич|производствен|цех|завод|промишлен"),
    ("Обществена", r"училище|детска градина|ясла|болница|поликлиник|читалище|спортна зала|храм|църква"),
    ("Гаражи / паркинг", r"гараж|паркинг"),
]


def classify(text: str) -> tuple[str, str]:
    low = (text or "").lower()
    kind = next((k for k, rx in KIND_RULES if re.search(rx, low)), "Друго")
    building = next((b for b, rx in BUILDING_RULES if re.search(rx, low)), "")
    return kind, building


def is_company(name: str) -> bool:
    return bool(re.search(LEGAL_FORMS, name or "")) or "ОБЩИНА" in (name or "").upper()


def split_investors(text: str) -> list[str]:
    """'"БИЛД 22" АД, КОСТАДИН ПЕТКОВ, ...' -> ['"БИЛД 22" АД', 'КОСТАДИН ПЕТКОВ', ...]"""
    return [re.sub(r"\s+", " ", part).strip() for part in (text or "").split(",") if part.strip()]


def companies_in(text: str) -> list[str]:
    return [p for p in split_investors(text) if re.search(LEGAL_FORMS, p)]


def score(lead: dict) -> int:
    s = 0
    s += {"Ново строителство": 40, "Надстрояване / пристрояване": 25, "Фасадна реновация": 35,
          "Инфраструктура": 15, "Преустройство / ремонт": 8,
          "Фотоволтаици": 8}.get(lead.get("kind"), 0)
    cat = lead.get("category")
    if cat:
        s += {1: 25, 2: 22, 3: 18, 4: 10, 5: 4, 6: 0}.get(cat, 0)
    rzp = lead.get("rzp_with_basement") or lead.get("rzp") or 0
    if rzp >= 10000:
        s += 25
    elif rzp >= 3000:
        s += 18
    elif rzp >= 1000:
        s += 12
    elif rzp >= 300:
        s += 5
    if lead.get("investor_is_company"):
        s += 10
    return min(s, 100)
