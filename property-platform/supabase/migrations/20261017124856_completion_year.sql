-- Кога се очаква сградата да е готова.
--
-- Не се ползва year_built: там стои годината, в която сградата Е построена.
-- При имот в строеж това още не е факт, а обещание, и двете не бива да
-- стоят в една колона — купувачът чете "2027" съвсем различно, когато
-- значи "построена 2027" и когато значи "обещано за 2027".
alter table public.listings
  add column if not exists completion_year smallint;

comment on column public.listings.completion_year is
  'Очаквана година на въвеждане в експлоатация при имот в строеж. За готов имот стои year_built.';
