-- Хранилището за снимки приемаше всякакъв файл с всякакъв размер:
-- влязъл потребител можеше да качи в своята папка видео, архив или
-- HTML страница и да ползва сайта като безплатен хостинг.
--
-- Всичките 19 113 файла в момента са JPEG, най-големият е 4,3 MB,
-- така че границите не засягат нищо качено.
update storage.buckets
   set file_size_limit = 10485760, -- 10 MB
       allowed_mime_types = array['image/jpeg', 'image/png', 'image/webp']
 where id = 'listing-photos';
