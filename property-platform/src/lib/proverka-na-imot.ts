/** Търсене в Google Maps — човекът вижда оценки и отзиви и избира сам. */
export function kartaZaTarsene(kakvo: string, grad: string) {
  const zayavka = [kakvo, grad.trim()].filter(Boolean).join(" ");
  return `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(zayavka)}`;
}

/** Готово писмо до юрист, с документите, които човекът вече е отметнал. */
export function pismoDoYurist(vid: Vid, grad: string, nalichni: string[]) {
  const kakvo =
    vid === "pokupka"
      ? "проверка на имот преди покупка"
      : "преглед на договор за наем и документите на наемодателя";
  const spisak = nalichni.length
    ? nalichni.map((d) => `- ${d}`).join("\n")
    : "- (ще изпратя документите, които имам)";
  return [
    "Здравейте,",
    "",
    `Търся юрист за ${kakvo}${grad.trim() ? ` в ${grad.trim()}` : ""}.`,
    "",
    "Разполагам със следните документи и мога да ги изпратя:",
    spisak,
    "",
    "Моля да ми кажете:",
    "1. Каква е цената на проверката и за колко време става.",
    "2. Нужни ли са Ви още документи.",
    "3. Ще получа ли писмено становище.",
    "",
    "Благодаря предварително.",
  ].join("\n");
}
